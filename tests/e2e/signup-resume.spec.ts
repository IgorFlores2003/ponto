import { test, expect } from '@playwright/test'

test('unfinished signup survives leaving and reload without storing the password', async ({ page }) => {
  await page.route('**/api/auth/config', route => route.fulfill({ json: { provider: 'local', registration_enabled: true } }))
  await page.route('**/api/auth/signup', route => route.fulfill({ status: 202, json: { message: 'Código enviado.' } }))
  await page.route('**/api/auth/verify-email', route => route.fulfill({ json: { message: 'E-mail confirmado.' } }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Teste')
  await page.getByLabel('E-mail', { exact: true }).fill('teste@example.com')
  await page.getByLabel('Senha (mínimo 10 caracteres)').fill('Password12345')
  await page.getByLabel('Confirmar senha').fill('Password12345')
  await page.getByRole('button', { name: 'Cadastrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Confirme seu e-mail' })).toBeVisible()
  await page.getByRole('button', { name: 'Voltar para entrar' }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('teste@example.com')
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('Password12345')
  await page.getByRole('button', { name: 'Informar código recebido' }).click()
  await page.getByLabel('Código de confirmação', { exact: true }).fill('123456')
  await page.getByRole('button', { name: 'Confirmar e-mail', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Aguardando aprovação' })).toBeVisible()
  await page.getByRole('button', { name: 'Voltar para entrar' }).click()
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Criar conta', exact: true })).toBeVisible()
})
